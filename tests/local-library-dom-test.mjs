import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";
import { JSDOM } from "jsdom";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = name => fs.readFile(path.join(root, name), "utf8");
const dom = new JSDOM(await read("index.html"), { url: "https://shelf.test/", runScripts: "outside-only", pretendToBeVisual: true });
const { window } = dom;
const checks = {};
const check = (name, condition) => { assert.ok(condition, name); checks[name] = true; };
const catalog = JSON.parse(await read("locales.json"));
window.fetch = async () => ({ ok: true, json: async () => catalog });
window.structuredClone = structuredClone;
window.scrollTo = () => {};
window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new window.Event("close")); };
const scripts = await Promise.all(["tests/bridge.js", "i18n.js", "parser.js", "library-filters.js", "app.js", "features.js", "filter-presets.js", "notifications.js"].map(read));
window.eval(scripts.join("\n;\n") + "\nwindow.testHarness = { messages: testMessages };");
window.document.dispatchEvent(new window.Event("DOMContentLoaded"));
await new Promise(resolve => setTimeout(resolve, 60));
await window.I18n.ready;
const element = id => window.document.getElementById(id);
element("local-view").click();
await new Promise(resolve => setTimeout(resolve, 40));
const card = window.document.querySelector("#grid .card");
check("localCardAvailable", Boolean(card));
check("noDownloadInLocalLibrary", !card.querySelector(".download-button"));
card.dispatchEvent(new window.MouseEvent("contextmenu", { bubbles: true, cancelable: true, clientX: 900, clientY: 600 }));
check("contextMenuOpens", !element("asset-menu").hidden && !element("local-dialog").open);
check("productUrlUsesItemId", element("asset-web").href === "https://booth.pm/ja/items/1");
window.document.dispatchEvent(new window.KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
check("escapeRestoresFocus", element("asset-menu").hidden && window.document.activeElement === card);
card.dispatchEvent(new window.KeyboardEvent("keydown", { key: "F10", shiftKey: true, bubbles: true, cancelable: true }));
check("keyboardContextMenu", !element("asset-menu").hidden);
window.document.dispatchEvent(new window.KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true, cancelable: true }));
check("keyboardMenuNavigation", window.document.activeElement === element("asset-delete"));
element("asset-delete").click();
await new Promise(resolve => setTimeout(resolve, 40));
check("deletePreviewsFolders", element("asset-delete-dialog").open && element("asset-delete-paths").textContent.includes("1_测试衣装"));
element("cancel-asset-delete").click();
check("cancelDoesNotDelete", !window.testHarness.messages.some(message => message.action === "local-asset-delete"));
card.dispatchEvent(new window.MouseEvent("contextmenu", { bubbles: true, cancelable: true, clientX: 200, clientY: 200 }));
element("asset-delete").click();
await new Promise(resolve => setTimeout(resolve, 30));
element("confirm-asset-delete").click();
await new Promise(resolve => setTimeout(resolve, 40));
check("deleteSendsItemAndConfirmedFolders", window.testHarness.messages.some(message => message.action === "local-asset-delete" && message.payload.itemId === "1" && message.payload.directories.length === 1));
check("deletedAssetDisappears", !window.document.querySelector("#grid .card") && !element("asset-delete-dialog").open);
const wheel = new window.WheelEvent("wheel", { bubbles: true, cancelable: true, deltaY: 500 });
element("window-chrome").dispatchEvent(wheel);
check("titleBarDoesNotScrollPage", wheel.defaultPrevented);
const pointerEvent = (type, clientX, clientY, button = 0) => new window.MouseEvent(type, { bubbles: true, cancelable: true, clientX, clientY, button });
for (const id of ["file-dialog", "local-dialog"]) {
  const dialog = element(id);
  dialog.getBoundingClientRect = () => ({ left: 200, right: 800, top: 150, bottom: 650 });
  dialog.showModal();
  dialog.dispatchEvent(pointerEvent("pointerdown", 210, 160));
  dialog.dispatchEvent(pointerEvent("click", 210, 160));
  check("dialogPaddingDoesNotDismiss_" + id, dialog.open);
  dialog.dispatchEvent(pointerEvent("pointerdown", 300, 300));
  dialog.dispatchEvent(pointerEvent("click", 100, 300));
  check("dragOutsideDoesNotDismiss_" + id, dialog.open);
  dialog.dispatchEvent(pointerEvent("pointerdown", 100, 300, 2));
  dialog.dispatchEvent(pointerEvent("click", 100, 300, 2));
  check("rightClickDoesNotDismiss_" + id, dialog.open);
  dialog.dispatchEvent(pointerEvent("pointerdown", 100, 300));
  dialog.dispatchEvent(pointerEvent("pointercancel", 100, 300));
  dialog.dispatchEvent(pointerEvent("click", 100, 300));
  check("canceledPointerDoesNotDismiss_" + id, dialog.open);
  const child = id === "local-dialog" ? element("file-menu") : element("file-title");
  child.hidden = false;
  child.dispatchEvent(pointerEvent("pointerdown", 900, 300));
  child.dispatchEvent(pointerEvent("click", 900, 300));
  check("dialogChildOutsideBoundsDoesNotDismiss_" + id, dialog.open);
  if (id === "local-dialog") element("file-menu").hidden = false;
  dialog.dispatchEvent(pointerEvent("pointerdown", 100, 300));
  dialog.dispatchEvent(pointerEvent("click", 100, 300));
  check("backdropClickDismisses_" + id, !dialog.open);
  if (id === "local-dialog") check("backdropCloseHidesFileMenu", element("file-menu").hidden);
}
for (const language of ["zh-CN", "zh-TW", "ja", "en", "ko"]) {
  window.I18n.set(language, language);
  check("translatedAssetActions_" + language, element("asset-web").textContent === window.I18n.t("打开商品网页")
    && element("asset-delete-description").textContent === window.I18n.t("整个资产文件夹及其中的所有文件（包括解压后的文件）将移到回收站。"));
}
dom.window.close();
const result = { passed: true, checks: Object.keys(checks).length, results: checks, environment: "jsdom; no real layout, account, or file deletion" };
await fs.writeFile(path.join(root, "tests/local-library-dom-result.json"), JSON.stringify(result, null, 2));
console.log(JSON.stringify({ passed: result.passed, checks: result.checks }));
